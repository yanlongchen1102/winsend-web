import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const MARKER = '<!-- Generated by scripts/build-site.mjs;';
const requiredPages = ['home', 'features', 'guides', 'download', 'setup', 'privacy', 'safety'];
const requiredUI = ['navigation', 'footerNavigation', 'home', 'features', 'guides', 'download', 'safety', 'privacy', 'language', 'menu', 'copyright', 'footerDescription', 'productScopeHeading', 'productScope', 'faqHeading'];
const read = (root, relative) => fs.readFileSync(path.join(root, relative), 'utf8').replace(/\r\n/g, '\n');
const readJSON = (root, relative) => JSON.parse(read(root, relative));
const digest = text => crypto.createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex');
export const escapeHTML = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

export function render(template, context) {
  return template.replace(/\{\{\{\s*([\w.-]+)\s*\}\}\}|\{\{\s*([\w.-]+)\s*\}\}/g, (_, rawKey, escapedKey) => {
    const key = rawKey || escapedKey;
    let value = context;
    for (const segment of key.split('.')) {
      if (value == null || !Object.hasOwn(value, segment)) throw new Error(`Unknown template variable: ${key}`);
      value = value[segment];
    }
    if (!['string', 'number', 'boolean'].includes(typeof value)) throw new Error(`Template variable must be scalar: ${key}`);
    return rawKey || key.startsWith('json.') ? String(value) : escapeHTML(value);
  }).replace(/^[\t ]+$/gm, '');
}

function requireText(value, label) {
  if (typeof value !== 'string' || !value.trim()) throw new Error(`Missing ${label}`);
}
function validateDate(value, label) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value || '') || new Date(value).toISOString().slice(0, 10) !== value) throw new Error(`Invalid date: ${label}`);
}
function outputPath(urlPath) {
  return urlPath === '/' ? 'index.html' : `${urlPath.slice(1)}index.html`;
}

export function loadSite(root = ROOT) {
  const config = readJSON(root, 'site/config.json');
  if (new URL(config.origin).origin !== config.origin || !config.origin.startsWith('https://')) throw new Error('origin must be an HTTPS origin without a trailing slash');
  validateDate(config.rootLastmod, 'rootLastmod');
  const codes = new Set();
  for (const locale of config.locales) {
    if (!/^[a-z]{2,3}(?:-[A-Z]{2})?$/.test(locale.code) || codes.has(locale.code)) throw new Error(`Invalid/duplicate locale: ${locale.code}`);
    codes.add(locale.code);
    if (!['published', 'draft'].includes(locale.status)) throw new Error(`Invalid locale status: ${locale.code}`);
    requireText(locale.name, `${locale.code}.name`);
    requireText(locale.htmlLang, `${locale.code}.htmlLang`);
  }
  const locales = config.locales.filter(locale => locale.status === 'published');
  if (!locales.some(locale => locale.code === config.defaultLocale)) throw new Error('Default locale must be published');
  const pages = [];
  const paths = new Set();
  const shared = {};
  const faqs = {};
  for (const locale of locales) {
    const dir = `site/content/${locale.code}`;
    const metadata = readJSON(root, `${dir}/pages.json`);
    shared[locale.code] = readJSON(root, `${dir}/shared.json`);
    faqs[locale.code] = fs.existsSync(path.join(root, `${dir}/faq.json`)) ? readJSON(root, `${dir}/faq.json`) : {};
    for (const key of requiredUI) requireText(shared[locale.code][key], `${locale.code}.shared.${key}`);
    const publishedIDs = new Set();
    for (const [id, data] of Object.entries(metadata)) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id)) throw new Error(`Invalid page ID: ${id}`);
      if (!['published', 'draft'].includes(data.status)) throw new Error(`Explicit page status required: ${locale.code}/${id}`);
      if (data.status !== 'published') continue;
      const expectedHomePath = locale.code === config.defaultLocale ? '/' : `/${locale.code}/`;
      const validPath = id === 'home'
        ? data.path === expectedHomePath
        : new RegExp(`^/${locale.code}/(?:[a-z0-9-]+/)*$`).test(data.path);
      if (!validPath || paths.has(data.path)) throw new Error(`Invalid/duplicate page path: ${data.path}`);
      paths.add(data.path);
      requireText(data.title, `${locale.code}/${id}.title`);
      requireText(data.description, `${locale.code}/${id}.description`);
      validateDate(data.lastmod, `${locale.code}/${id}.lastmod`);
      if (id === 'home' && data.path !== expectedHomePath) throw new Error('Home must use its locale root');
      if (!['fixed', 'flow'].includes(data.navigationMode ?? 'fixed')) throw new Error('navigationMode must be fixed or flow');
      if (data.robots && /noindex|nofollow/i.test(data.robots)) throw new Error(`Published pages must be indexable: ${locale.code}/${id}`);
      if (data.layout && !['home', 'features', 'guides', 'download'].includes(data.layout)) throw new Error(`Unknown shared layout: ${data.layout}`);
      const copy = data.layout ? readJSON(root, `${dir}/${id}.copy.json`) : {};
      const cards = data.layout === 'guides' ? readJSON(root, `${dir}/${id}.cards.json`) : [];
      pages.push({ ...data, copy, cards, id, locale, head: read(root, `${dir}/${id}.head.html`), body: read(root, `${dir}/${id}.body.html`) });
      publishedIDs.add(id);
    }
    for (const id of requiredPages) if (!publishedIDs.has(id)) throw new Error(`Published locale ${locale.code} needs its reviewed ${id} page`);
  }
  const product = readJSON(root, 'site/product.json');
  for (const key of ['name', 'iosMinimum', 'shortcutsMinimum', 'microsoftStoreUrl', 'appStoreUrl']) requireText(product[key], `product.${key}`);
  return { config, locales, pages, shared, faqs, product };
}

function alternates(site, page) {
  const result = site.pages.filter(candidate => candidate.id === page.id).map(candidate => ({ lang: candidate.locale.code, path: candidate.path }));
  if (page.id === 'home') result.push({ lang: 'x-default', path: '/' });
  else {
    const fallback = result.find(link => link.lang === site.config.defaultLocale);
    if (fallback) result.push({ lang: 'x-default', path: fallback.path });
  }
  return result;
}
function seoHTML(site, data, alternateLinks) {
  const canonical = site.config.origin + data.path;
  return [
    `    <title>${escapeHTML(data.title)}</title>`,
    `    <meta name="description" content="${escapeHTML(data.description)}">`,
    `    <meta name="robots" content="${escapeHTML(data.robots || 'index,follow,max-image-preview:large')}">`,
    `    <link rel="canonical" href="${escapeHTML(canonical)}">`,
    ...alternateLinks.map(link => `    <link rel="alternate" hreflang="${link.lang}" href="${escapeHTML(site.config.origin + link.path)}">`),
    `    <meta property="og:title" content="${escapeHTML(data.title)}">`,
    `    <meta property="og:description" content="${escapeHTML(data.description)}">`,
    `    <meta property="og:url" content="${escapeHTML(canonical)}">`,
    `    <meta property="og:locale" content="${escapeHTML((data.htmlLang || data.locale.htmlLang).replaceAll('-', '_'))}">`,
    `    <meta name="twitter:title" content="${escapeHTML(data.title)}">`,
    `    <meta name="twitter:description" content="${escapeHTML(data.description)}">`,
  ].join('\n');
}
function localLinks(site, locale) {
  return Object.fromEntries(site.pages.filter(page => page.locale.code === locale.code).map(page => [page.id, page.path]));
}
function linkList(ids, links, ui, currentID, navigation = false) {
  return ids.filter(id => links[id]).map(id => {
    const classes = navigation ? (id === 'download' ? 'site-download-link' : 'site-secondary-link') : '';
    const current = currentID === id ? ' aria-current="page"' : '';
    return `<a href="${escapeHTML(links[id])}"${classes ? ` class="${classes}"` : ''}${current}>${escapeHTML(ui[id])}</a>`;
  }).join('');
}

export function generateSite(root = ROOT) {
  const site = loadSite(root);
  const templates = Object.fromEntries(['page', 'navigation', 'footer', 'product-scope', 'faq', 'faq-item', 'page-header', 'layout-home', 'layout-features', 'layout-guides', 'layout-download', 'guide-card'].map(name => [name, read(root, `site/templates/${name}.html`)]));
  const outputs = new Map();
  for (const page of site.pages) {
    const ui = site.shared[page.locale.code];
    const links = localLinks(site, page.locale);
    const canonical = site.config.origin + page.path;
    const navigationIDs = ui.navigationPages || ['features', 'guides', 'download'];
    if (!Array.isArray(navigationIDs) || ['features', 'guides', 'download'].some(id => !navigationIDs.includes(id)) || navigationIDs.some(id => typeof id !== 'string' || !Object.hasOwn(ui, id) || (ui.navigationPages && !links[id]))) throw new Error(`${page.locale.code}: invalid navigationPages`);
    const context = {
      ui, links, copy: page.copy, presentation: page.presentation || {}, urls: Object.fromEntries(Object.entries(links).map(([id, link]) => [id, site.config.origin + link])),
      product: { ...site.product, appStoreUrl: ui.appStoreUrl || site.product.appStoreUrl }, htmlLang: page.locale.htmlLang, localeName: page.locale.name, localeCode: page.locale.code, pageID: page.id,
      canonical, lastmod: page.lastmod, title: page.title, description: page.description,
      bodyClass: page.bodyClass || 'bg-white text-gray-900 antialiased', navigationMode: page.navigationMode || 'fixed',
      copyrightYear: site.config.rootLastmod.slice(0, 4),
      navigationLinks: linkList(navigationIDs, links, ui, page.id, true),
      pageMenuLinks: linkList(navigationIDs, links, ui, page.id),
      footerLinks: linkList([...new Set([...navigationIDs, 'safety', 'privacy'])], links, ui, page.id),
      languageLinks: site.pages.filter(candidate => candidate.id === page.id).map(candidate => `<a href="${escapeHTML(candidate.path)}" lang="${candidate.locale.htmlLang}" hreflang="${candidate.locale.code}"${candidate.locale.code === page.locale.code ? ' aria-current="page"' : ''}>${escapeHTML(candidate.locale.name)}</a>`).join(''),
      // Use json.* inside a quoted JSON-LD string to avoid HTML entity escaping.
      json: Object.fromEntries(Object.entries({ title: page.title, description: page.description, canonical }).map(([key, value]) => [key, JSON.stringify(value).slice(1, -1).replace(/[<>&]/g, char => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`)])),
    };
    context.pageHeader = page.body.includes('{{{pageHeader}}}') ? render(templates['page-header'], context) : '';
    context.productScope = render(templates['product-scope'], context);
    const questions = site.faqs[page.locale.code][page.id] || [];
    if (!Array.isArray(questions)) throw new Error(`FAQ list must be an array: ${page.locale.code}/${page.id}`);
    const names = new Set();
    for (const item of questions) {
      requireText(item.question, `${page.id}.FAQ.question`);
      requireText(item.answer, `${page.id}.FAQ.answer`);
      if (names.has(item.question)) throw new Error(`Duplicate FAQ question: ${page.id}/${item.question}`);
      names.add(item.question);
    }
    if ((page.body.includes('{{{faq}}}') || (page.layout && templates[`layout-${page.layout}`].includes('{{{faq}}}'))) && !questions.length) throw new Error(`Missing reviewed FAQ copy: ${page.locale.code}/${page.id}`);
    context.faqItems = questions.map(item => render(templates['faq-item'], item)).join('');
    context.faq = questions.length ? render(templates.faq, context) : '';
    context.faqSchema = questions.length ? '    <script type="application/ld+json">' + JSON.stringify({
      '@context': 'https://schema.org', '@type': 'FAQPage',
      mainEntity: questions.map(item => ({ '@type': 'Question', name: item.question, acceptedAnswer: { '@type': 'Answer', text: item.answer } })),
    }).replace(/[<>&]/g, char => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`) + '</script>' : '';
    if (!Array.isArray(page.cards)) throw new Error(`${page.locale.code}/${page.id}: cards must be an array`);
    context.guideCards = page.cards.map(card => {
      if (!links[card.page]) throw new Error(`${page.locale.code}/${page.id}: unpublished guide card ${card.page}`);
      for (const field of ['category', 'title', 'description', 'cta']) requireText(card[field], `guide card ${field}`);
      return render(templates['guide-card'], { card: { ...card, href: links[card.page] } });
    }).join('\n');
    context.pageLayout = page.layout ? render(templates[`layout-${page.layout}`], context) : '';
    context.head = render(page.head, context);
    context.body = render(page.body, context);
    context.navigation = render(templates.navigation, context);
    context.footer = render(templates.footer, context);
    context.seo = seoHTML(site, page, alternates(site, page));
    const output = render(templates.page, context);
    validatePage(site, page, output);
    outputs.set(outputPath(page.path), output);
  }
  const urls = site.pages;
  const xml = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">'];
  for (const page of urls) {
    xml.push('  <url>', `    <loc>${escapeHTML(site.config.origin + page.path)}</loc>`, `    <lastmod>${page.lastmod}</lastmod>`);
    for (const link of alternates(site, page)) xml.push(`    <xhtml:link rel="alternate" hreflang="${link.lang}" href="${escapeHTML(site.config.origin + link.path)}" />`);
    xml.push('  </url>');
  }
  outputs.set('sitemap.xml', xml.concat('</urlset>', '').join('\n'));
  validateInternalLinks(site, outputs);
  return { site, outputs };
}

export function validateInternalLinks(site, outputs) {
  for (const [file, html] of outputs) {
    if (!file.endsWith('.html')) continue;
    const sourcePath = file === 'index.html' ? '/' : '/' + file.replace(/index\.html$/, '');
    for (const match of html.matchAll(/<a\b[^>]*\bhref="([^"]+)"/g)) {
      const href = decodeHTML(match[1]);
      if (!href || href === '#') continue;
      const url = new URL(href, site.config.origin + sourcePath);
      if (url.origin !== site.config.origin || /\.[a-z0-9]+$/i.test(url.pathname)) continue;
      const targetPath = url.pathname.endsWith('/') ? url.pathname : url.pathname + '/';
      const target = outputs.get(outputPath(targetPath));
      if (!target) throw new Error(`${file}: broken internal page link: ${href}`);
      if (url.hash) {
        const anchor = decodeURIComponent(url.hash.slice(1));
        const ids = [...target.matchAll(/\sid="([^"]+)"/g)].map(item => item[1]);
        if (!ids.includes(anchor)) throw new Error(`${file}: missing link anchor: ${href}`);
      }
    }
  }
}

function decodeHTML(value) {
  return value.replace(/&(?:amp|lt|gt|quot|#39);/g, entity => ({ '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'" })[entity]);
}
export function validatePage(site, page, output) {
  const label = `${page.locale.code}/${page.id}`;
  if (/\{\{/.test(output)) throw new Error(`${label}: unresolved template variable`);
  if (/<meta[^>]+http-equiv=["']refresh/i.test(output) || /(?:window\.)?location\.(?:href|replace|assign)\s*[=(]/.test(output)) throw new Error(`${label}: automatic redirects are not allowed`);
  const canonicals = [...output.matchAll(/<link rel="canonical" href="([^"]+)"/g)];
  if (canonicals.length !== 1 || decodeHTML(canonicals[0][1]) !== site.config.origin + page.path) throw new Error(`${label}: canonical mismatch`);
  if (!output.includes(`<html lang="${page.locale.htmlLang}"`)) throw new Error(`${label}: html language mismatch`);
  const ids = [...output.matchAll(/\sid="([^"]+)"/g)].map(match => match[1]);
  if (new Set(ids).size !== ids.length) throw new Error(`${label}: duplicate HTML IDs`);
  const body = output.split('<body')[1].replace(/<script\b[^>]*>[\s\S]*?<\/script>|<style\b[^>]*>[\s\S]*?<\/style>/g, '');
  if ([...body.matchAll(/<main(?:\s|>)/g)].length !== 1 || [...body.matchAll(/<h1(?:\s|>)/g)].length !== 1) throw new Error(`${label}: a published page needs one main landmark and one H1`);
  const visible = decodeHTML(body.replace(/<[^>]*>/g, ' ')).replace(/\s+/g, ' ');
  for (const match of output.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    let data;
    try { data = JSON.parse(match[1]); } catch (error) { throw new Error(`${label}: invalid JSON-LD: ${error.message}`); }
    const nodes = Array.isArray(data) ? data : (data['@graph'] || [data]);
    for (const node of nodes) if (node['@type'] === 'FAQPage') {
      for (const question of node.mainEntity || []) {
        for (const text of [question.name, question.acceptedAnswer.text]) if (!visible.includes(text.replace(/\s+/g, ' '))) throw new Error(`${label}: FAQ not visible: ${text}`);
      }
    }
  }
  const expected = alternates(site, page);
  const actual = [...output.matchAll(/<link rel="alternate" hreflang="([^"]+)" href="([^"]+)"/g)];
  if (actual.length !== expected.length || expected.some(link => !actual.some(match => match[1] === link.lang && decodeHTML(match[2]) === site.config.origin + link.path))) throw new Error(`${label}: hreflang mismatch`);
}

export function buildSite({ root = ROOT, check = false } = {}) {
  const { site, outputs } = generateSite(root);
  const statePath = 'site/generated.json';
  const previous = fs.existsSync(path.join(root, statePath)) ? readJSON(root, statePath) : {};
  const changes = [];
  // Detect hand-edited generated output before overwriting it. Source edits are
  // expected; changes to the generated files must be moved back into site/content.
  for (const [relative, text] of outputs) {
    const file = path.join(root, relative);
    const current = fs.existsSync(file) ? read(root, relative) : null;
    if (current !== text) {
      if (!check && previous[relative] && current !== null && digest(current) !== previous[relative]) throw new Error(`Generated output was edited by hand: ${relative}. Move edits to site/content first.`);
      changes.push(relative);
    }
  }
  const stale = Object.keys(previous).filter(relative => !outputs.has(relative));
  for (const relative of stale) {
    if (!/^(?:[a-z]{2,3}(?:-[A-Z]{2})?\/)?(?:[a-z0-9-]+\/)*index\.html$/.test(relative)) throw new Error(`Refusing unsafe stale path: ${relative}`);
    if (fs.existsSync(path.join(root, relative))) {
      const current = read(root, relative);
      if (!current.includes(MARKER) || digest(current) !== previous[relative]) throw new Error(`Refusing to remove modified/unmanaged file: ${relative}`);
      changes.push(`remove ${relative}`);
    }
  }
  const state = JSON.stringify(Object.fromEntries([...outputs].map(([name, text]) => [name, digest(text)])), null, 2) + '\n';
  if (!fs.existsSync(path.join(root, statePath)) || read(root, statePath) !== state) changes.push(statePath);
  if (check) {
    if (changes.length) throw new Error(`Generated files are stale; run npm run build:site:\n${changes.join('\n')}`);
  } else {
    // All source/render checks and overwrite guards finish before writing files.
    for (const [relative, text] of outputs) {
      const file = path.join(root, relative);
      if (fs.existsSync(file) && read(root, relative) === text) continue;
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(`${file}.site-tmp`, text);
      fs.renameSync(`${file}.site-tmp`, file);
    }
    for (const relative of stale) if (fs.existsSync(path.join(root, relative))) fs.unlinkSync(path.join(root, relative));
    fs.writeFileSync(path.join(root, statePath), state);
  }
  return { pages: site.pages.length, locales: site.locales.map(locale => locale.code), changes };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = buildSite({ check: process.argv.includes('--check') });
    console.log(`${process.argv.includes('--check') ? 'Checked' : 'Built'} ${result.pages} content pages; published locales: ${result.locales.join(', ')}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
